from __future__ import annotations

from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

from app.models import Invoice, Organization


PRIMARY = colors.HexColor("#063533")
MUTED = colors.HexColor("#667272")
LINE = colors.HexColor("#E4E7E7")


def invoice_pdf(org: Organization, inv: Invoice) -> bytes:
    buf = BytesIO()
    c = canvas.Canvas(buf, pagesize=A4)
    w, h = A4
    y = h - 22 * mm

    c.setFillColor(PRIMARY)
    c.rect(0, h - 18 * mm, w, 18 * mm, fill=1, stroke=0)
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 14)
    c.drawString(18 * mm, h - 12 * mm, "SUPERFINANCE")
    c.setFont("Helvetica", 9)
    c.drawRightString(w - 18 * mm, h - 12 * mm, "TAX INVOICE")

    y = h - 32 * mm
    c.setFillColor(PRIMARY)
    c.setFont("Helvetica-Bold", 11)
    c.drawString(18 * mm, y, org.legal_name or org.name)
    c.setFillColor(MUTED)
    c.setFont("Helvetica", 9)
    c.drawString(18 * mm, y - 12, f"GSTIN {org.gstin or '—'}")
    c.setFillColor(PRIMARY)
    c.setFont("Helvetica-Bold", 12)
    c.drawRightString(w - 18 * mm, y, inv.number)
    c.setFont("Helvetica", 9)
    c.setFillColor(MUTED)
    c.drawRightString(w - 18 * mm, y - 12, f"Date {inv.invoice_date.isoformat()}  ·  Due {inv.due_date.isoformat()}")

    y -= 36
    c.setStrokeColor(LINE)
    c.line(18 * mm, y, w - 18 * mm, y)
    y -= 18
    c.setFillColor(MUTED)
    c.setFont("Helvetica", 8)
    c.drawString(18 * mm, y, "BILL TO")
    y -= 14
    c.setFillColor(PRIMARY)
    c.setFont("Helvetica-Bold", 10)
    client_name = inv.client.name if inv.client else "Client"
    c.drawString(18 * mm, y, client_name)
    y -= 12
    c.setFont("Helvetica", 9)
    c.setFillColor(MUTED)
    if inv.gstin:
        c.drawString(18 * mm, y, f"GSTIN {inv.gstin}")
        y -= 12
    if inv.billing_address:
        for line in (inv.billing_address or "").split("\n")[:3]:
            c.drawString(18 * mm, y, line[:90])
            y -= 12

    y -= 8
    c.setFillColor(PRIMARY)
    c.setFont("Helvetica-Bold", 8)
    c.drawString(18 * mm, y, "DESCRIPTION")
    c.drawRightString(130 * mm, y, "QTY")
    c.drawRightString(160 * mm, y, "RATE")
    c.drawRightString(w - 18 * mm, y, "AMOUNT")
    y -= 6
    c.setStrokeColor(LINE)
    c.line(18 * mm, y, w - 18 * mm, y)
    y -= 14
    c.setFont("Helvetica", 9)
    c.setFillColor(colors.HexColor("#172121"))
    for item in inv.items:
        c.drawString(18 * mm, y, (item.description or "")[:48])
        c.drawRightString(130 * mm, y, f"{float(item.quantity):g}")
        c.drawRightString(160 * mm, y, f"INR {float(item.rate):,.0f}")
        c.drawRightString(w - 18 * mm, y, f"INR {float(item.amount):,.0f}")
        y -= 14

    y -= 8
    c.line(120 * mm, y, w - 18 * mm, y)
    y -= 16
    c.setFont("Helvetica", 9)
    c.drawString(120 * mm, y, "Subtotal")
    c.drawRightString(w - 18 * mm, y, f"INR {float(inv.subtotal):,.0f}")
    y -= 14
    c.drawString(120 * mm, y, "GST")
    c.drawRightString(w - 18 * mm, y, f"INR {float(inv.tax_amount):,.0f}")
    y -= 16
    c.setFont("Helvetica-Bold", 11)
    c.setFillColor(PRIMARY)
    c.drawString(120 * mm, y, "Total")
    c.drawRightString(w - 18 * mm, y, f"INR {float(inv.total):,.0f}")
    y -= 16
    c.setFont("Helvetica", 9)
    c.setFillColor(MUTED)
    c.drawString(120 * mm, y, f"Paid INR {float(inv.amount_paid):,.0f}")
    y -= 12
    due = float(inv.total - inv.amount_paid)
    c.drawString(120 * mm, y, f"Balance due INR {due:,.0f}")

    c.setFillColor(MUTED)
    c.setFont("Helvetica", 8)
    c.drawString(18 * mm, 16 * mm, (inv.payment_terms or "Net 30") + "  ·  Generated by SUPERFINANCE")
    c.showPage()
    c.save()
    return buf.getvalue()
